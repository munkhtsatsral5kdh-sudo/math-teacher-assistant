  function topicsOf(grade) {
    return (window.CURRICULUM[String(grade)] || []);
  }

  function contentUnits(grade) {
    const topics = topicsOf(grade);
    const byKey = Object.fromEntries(topics.map((t) => [t.key, t]));
    return (CONTENT_UNITS[Number(grade)] || []).map((unit) => ({
      name: unit.name,
      topics: unit.keys.map((key) => byKey[key]).filter(Boolean),
    })).filter((unit) => unit.topics.length);
  }

  function unitName(topicKey) {
    const grade = Number(String(topicKey).split("-")[0]);
    const unit = (CONTENT_UNITS[grade] || []).find((u) => u.keys.includes(topicKey));
    return unit ? unit.name : "";
  }

  function generate(topicKey, level) {
    const g = GEN[topicKey];
    if (!g) return null;
    return g(level);
  }

  function buildQuestions({ grade, topicKey = null, count = 10, level = null, bankFirst = true }) {
    const keys = topicKey ? [topicKey] : topicsOf(grade).map((t) => t.key);
    let bank = [];
    keys.forEach((k) => (RAW[k] || []).forEach((p) => bank.push({ p, k })));
    if (level) bank = bank.filter(({ p }) => p.level === level);
    bank.sort(() => Math.random() - 0.5);
    const out = [];
    const bankShare = bankFirst ? Math.min(bank.length, Math.ceil(count * 0.6)) : 0;
    bank.slice(0, bankShare).forEach(({ p, k }) => out.push(instantiate(p, grade, k, "bank")));
    const seen = new Set(out.map((q) => q.text));
    let guard = 0;
    while (out.length < count && guard < count * 30) {
      guard += 1;
      const k = keys[Math.floor(Math.random() * keys.length)];
      const lvl = level || ri(1, 3);
      const q = generate(k, lvl);
      if (!q || seen.has(q.text)) continue;
      seen.add(q.text);
      out.push(instantiate(q, grade, k, "gen"));
    }
    return out.sort(() => Math.random() - 0.5);
  }

  function unitsFor(topicKey) {
    const t = THEORY[topicKey];
    if (!t) return [];
    const out = [{ topicKey, name: t.name, theory: t.theory }];
    const lesson = LESSON[topicKey];
    if (lesson) {
      lesson.examples.forEach(([q, sol], i) => out.push({ topicKey, name: `Жишээ ${i + 1}. ${q}`, theory: `Бодолт: ${sol}` }));
      const marks = ["①", "②", "③", "④", "⑤", "⑥"];
      out.push({ topicKey, name: "Сурагчдын түгээмэл алдаа", theory: lesson.mistakes.map((m, i) => `${marks[i] || "•"} ${m}`).join("  ") });
    }
    const gloss = window.GLOSSARY_MATH ? (window.GLOSSARY_MATH[topicKey.split("-")[0]] || []).filter((g) => g.topic === topicKey) : [];
    if (gloss.length) out.push({ topicKey, name: "Нэр томьёо", theory: gloss.map((g) => `${g.term} — ${g.def}`).join(" • ") });
    return out;
  }

  function bankCount(topicKey) {
    return (RAW[topicKey] || []).length;
  }

  function topicTitle(key) {
    const [g] = key.split("-");
    const t = topicsOf(g).find((x) => x.key === key);
    return t ? niceTitle(t.title) : key;
  }

  function niceTitle(title) {
    const lower = title.toLocaleLowerCase("mn");
    return lower.charAt(0).toLocaleUpperCase("mn") + lower.slice(1);
  }

